import React, { useState, useEffect } from 'react';
import {
  X,
  FileText,
  Sparkles,
  Download,
  CheckCircle2,
  AlertTriangle,
  Wrench,
  Clock,
  ShieldCheck,
  Edit3,
  Save,
  Plus,
  Trash2,
} from 'lucide-react';
import { jsPDF } from 'jspdf';
import type { BookingRecord, RepairReportRecord, RepairReportPart } from '../types';
import type { LanguageCode } from '../i18n/translations';

interface RepairReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  booking: BookingRecord;
  token: string;
  userRole: 'CUSTOMER' | 'WORKER' | 'ADMIN';
  t: Record<string, string>;
  lang?: LanguageCode;
  onReportSaved?: (report: RepairReportRecord) => void;
}

export const RepairReportModal: React.FC<RepairReportModalProps> = ({
  isOpen,
  onClose,
  booking,
  token,
  userRole,
  t,
  lang = 'en',
  onReportSaved,
}) => {
  const [report, setReport] = useState<RepairReportRecord | null>(null);
  const [loading, setLoading] = useState(false);
  const [generating, setGenerating] = useState(false);
  const [saving, setSaving] = useState(false);
  const [isEditing, setIsEditing] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [successNotice, setSuccessNotice] = useState<string | null>(null);

  // Editable fields
  const [title, setTitle] = useState('');
  const [originalProblem, setOriginalProblem] = useState('');
  const [workPerformed, setWorkPerformed] = useState<string[]>([]);
  const [parts, setParts] = useState<RepairReportPart[]>([]);
  const [outstandingIssues, setOutstandingIssues] = useState<string[]>([]);
  const [maintenanceSuggestions, setMaintenanceSuggestions] = useState<string[]>([]);
  const [customerSummary, setCustomerSummary] = useState('');

  // New item draft inputs for editing
  const [newWorkItem, setNewWorkItem] = useState('');
  const [newOutstandingItem, setNewOutstandingItem] = useState('');
  const [newMaintenanceItem, setNewMaintenanceItem] = useState('');
  const [newPartName, setNewPartName] = useState('');
  const [newPartQty, setNewPartQty] = useState('1');
  const [newPartCost, setNewPartCost] = useState('');

  // Fetch existing report on open
  useEffect(() => {
    if (!isOpen || !booking.id) return;
    setError(null);
    setSuccessNotice(null);
    setLoading(true);

    fetch(`/api/ai/repair-report/${booking.id}`, {
      headers: { Authorization: `Bearer ${token}` },
    })
      .then((res) => {
        if (res.ok) return res.json();
        return null;
      })
      .then((data) => {
        if (data?.report) {
          populateReportData(data.report);
        } else {
          setReport(null);
          setTitle(`${booking.workerCategory} Completion Report — ${booking.bookingReference}`);
          setOriginalProblem(booking.problemDescription || '');
        }
      })
      .catch((err) => {
        console.warn('Could not fetch existing repair report:', err);
      })
      .finally(() => {
        setLoading(false);
      });
  }, [isOpen, booking.id, token]);

  const populateReportData = (rep: RepairReportRecord) => {
    setReport(rep);
    setTitle(rep.reportTitle);
    setOriginalProblem(rep.originalReportedProblem);
    setWorkPerformed(rep.workPerformed || []);
    setParts(rep.partsUsed || []);
    setOutstandingIssues(
      Array.isArray(rep.outstandingIssues)
        ? (rep.outstandingIssues as any)
        : rep.outstandingIssues
        ? [rep.outstandingIssues]
        : []
    );
    setMaintenanceSuggestions(rep.maintenanceSuggestions || []);
    setCustomerSummary(rep.customerSummary || '');
  };

  const handleGenerateReport = async () => {
    setGenerating(true);
    setError(null);
    setSuccessNotice(null);

    try {
      const res = await fetch('/api/ai/repair-report/generate', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${token}`,
        },
        body: JSON.stringify({
          bookingId: booking.id,
          workerNotes: [booking.problemDescription],
          completedChecklist: ['Visual safety inspection', 'Trade repair execution', 'Functional verification'],
        }),
      });

      const data = await res.json();
      if (!res.ok) {
        throw new Error(data.error || 'Failed to generate repair report.');
      }

      if (data.report) {
        populateReportData(data.report);
        setIsEditing(true); // Allow worker to review and edit immediately
        setSuccessNotice('Draft report generated by Gemma 4. Please review and edit before approving.');
      }
    } catch (err: any) {
      setError(err instanceof Error ? err.message : 'Error generating report.');
    } finally {
      setGenerating(false);
    }
  };

  const handleSaveAndApprove = async () => {
    setSaving(true);
    setError(null);
    setSuccessNotice(null);

    const reportId = report?.id || `rep-${Date.now()}`;
    try {
      const res = await fetch(`/api/ai/repair-report/${reportId}`, {
        method: 'PUT',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${token}`,
        },
        body: JSON.stringify({
          bookingId: booking.id,
          bookingReference: booking.bookingReference,
          reportTitle: title,
          originalReportedProblem: originalProblem,
          workPerformed,
          partsUsed: parts,
          outstandingIssues,
          maintenanceSuggestions,
          customerSummary,
          approve: true,
        }),
      });

      const data = await res.json();
      if (!res.ok) {
        throw new Error(data.error || 'Failed to save repair report.');
      }

      if (data.report) {
        setReport(data.report);
        setIsEditing(false);
        setSuccessNotice('Repair report saved and verified. Customer can view verified service report.');
        if (onReportSaved) {
          onReportSaved(data.report);
        }
      }
    } catch (err: any) {
      setError(err instanceof Error ? err.message : 'Error saving report.');
    } finally {
      setSaving(false);
    }
  };

  const handleDownloadPdf = () => {
    const doc = new jsPDF();
    const currentTitle = title || `${booking.workerCategory} Completion Report`;

    // Header Band
    doc.setFillColor(7, 94, 84); // Deep Teal
    doc.rect(0, 0, 210, 32, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(16);
    doc.text('HELP NEST COOPERATIVE SERVICES', 14, 14);
    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.text('Certified Household & Community Repair Completion Report', 14, 22);
    doc.text(`Booking Ref: ${booking.bookingReference}`, 140, 22);

    let y = 42;
    doc.setTextColor(36, 49, 44);

    // Meta details
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.text(currentTitle, 14, y);
    y += 8;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.text(`Customer: ${booking.customerName} (${booking.customerPhone})`, 14, y);
    doc.text(`Servicing Worker: ${booking.workerName} (${booking.workerCategory})`, 110, y);
    y += 6;
    doc.text(`Date of Service: ${booking.preferredDate} (${booking.preferredTimeSlot})`, 14, y);
    doc.text(`Status: Verified Cooperative Completed Job`, 110, y);
    y += 10;

    // Divider
    doc.setDrawColor(200, 214, 205);
    doc.line(14, y, 196, y);
    y += 8;

    // Original Problem
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('1. Reported Customer Issue:', 14, y);
    y += 6;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    const splitProblem = doc.splitTextToSize(originalProblem || booking.problemDescription || 'N/A', 180);
    doc.text(splitProblem, 14, y);
    y += splitProblem.length * 5 + 4;

    // Work Performed
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('2. Work Performed On-Site:', 14, y);
    y += 6;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    if (workPerformed.length === 0) {
      doc.text('- Diagnostic trade inspection and corrective repair completed.', 16, y);
      y += 6;
    } else {
      for (const item of workPerformed) {
        doc.text(`• ${item}`, 16, y);
        y += 5;
      }
    }
    y += 4;

    // Parts Used
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('3. Confirmed Replacement Parts & Hardware:', 14, y);
    y += 6;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    if (parts.length === 0) {
      doc.text('None — Service completed using existing hardware/labor only.', 16, y);
      y += 6;
    } else {
      for (const p of parts) {
        doc.text(`• ${p.name} (Qty: ${p.quantity}${p.costInr ? `, ₹${p.costInr}` : ''})`, 16, y);
        y += 5;
      }
    }
    y += 4;

    // Outstanding Issues
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('4. Outstanding Issues:', 14, y);
    y += 6;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    for (const oi of outstandingIssues.length > 0 ? outstandingIssues : ['None — Issue resolved.']) {
      doc.text(`• ${oi}`, 16, y);
      y += 5;
    }
    y += 4;

    // Maintenance Suggestions
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('5. Preventative Maintenance Suggestions:', 14, y);
    y += 6;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    for (const ms of maintenanceSuggestions.length > 0 ? maintenanceSuggestions : ['Inspect fixture periodically.']) {
      doc.text(`• ${ms}`, 16, y);
      y += 5;
    }
    y += 6;

    // Customer Summary
    if (customerSummary) {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.text('6. Summary for Customer:', 14, y);
      y += 6;
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      const splitSummary = doc.splitTextToSize(customerSummary, 180);
      doc.text(splitSummary, 14, y);
      y += splitSummary.length * 5 + 6;
    }

    // Footer note
    doc.setDrawColor(200, 214, 205);
    doc.line(14, 275, 196, 275);
    doc.setFontSize(8);
    doc.setTextColor(100, 115, 105);
    doc.text('Help Nest Cooperative Society · Fair 90:10 Worker Settlement · Certified Member Service', 14, 282);
    doc.text(`Generated: ${new Date().toLocaleString()}`, 145, 282);

    doc.save(`HelpNest_Report_${booking.bookingReference}.pdf`);
  };

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-xs overflow-y-auto">
      <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-2xl w-full max-w-3xl shadow-2xl overflow-hidden my-6 max-h-[92vh] flex flex-col">
        {/* Header */}
        <div className="p-5 border-b border-slate-100 dark:border-slate-800 bg-linear-to-r from-teal-50/80 to-emerald-50/50 dark:from-slate-850 dark:to-slate-900 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-teal-700/10 dark:bg-teal-500/20 text-teal-700 dark:text-teal-400 flex items-center justify-center font-bold">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="text-lg font-bold text-slate-900 dark:text-white font-display">
                  {t.repairReportTitle || 'Verified Service & Completion Report'}
                </h3>
                {report?.workerApprovedAt && (
                  <span className="text-xs px-2 py-0.5 rounded-full bg-emerald-100 dark:bg-emerald-950/60 text-emerald-700 dark:text-emerald-400 font-semibold border border-emerald-300 dark:border-emerald-800 flex items-center gap-1">
                    <CheckCircle2 className="w-3 h-3" /> Verified
                  </span>
                )}
              </div>
              <p className="text-xs text-slate-500 dark:text-slate-400">
                Booking Reference: <span className="font-mono font-semibold text-teal-700 dark:text-teal-400">{booking.bookingReference}</span> · {booking.workerCategory}
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 rounded-lg text-slate-400 hover:text-slate-600 dark:hover:text-slate-200 hover:bg-slate-100 dark:hover:bg-slate-800 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Notices */}
        {error && (
          <div className="mx-6 mt-4 p-3 rounded-xl bg-rose-50 dark:bg-rose-950/40 border border-rose-200 dark:border-rose-900/50 text-rose-700 dark:text-rose-400 text-xs flex items-center gap-2">
            <AlertTriangle className="w-4 h-4 shrink-0" />
            <span>{error}</span>
          </div>
        )}
        {successNotice && (
          <div className="mx-6 mt-4 p-3 rounded-xl bg-emerald-50 dark:bg-emerald-950/40 border border-emerald-200 dark:border-emerald-900/50 text-emerald-700 dark:text-emerald-400 text-xs flex items-center gap-2">
            <CheckCircle2 className="w-4 h-4 shrink-0" />
            <span>{successNotice}</span>
          </div>
        )}

        {/* Modal Body */}
        <div className="p-6 overflow-y-auto space-y-5 flex-1">
          {loading ? (
            <div className="py-12 text-center text-slate-500 dark:text-slate-400">
              <Clock className="w-8 h-8 animate-spin mx-auto text-teal-700 mb-2" />
              <p className="text-sm font-medium">Loading service report records...</p>
            </div>
          ) : !report && !isEditing ? (
            <div className="text-center py-10 px-4 rounded-xl border border-dashed border-slate-300 dark:border-slate-700 bg-slate-50/50 dark:bg-slate-850/40">
              <Sparkles className="w-10 h-10 mx-auto text-teal-700 mb-3 opacity-80" />
              <h4 className="text-base font-bold text-slate-900 dark:text-white mb-1">
                No Certified Service Report Generated Yet
              </h4>
              <p className="text-xs text-slate-500 dark:text-slate-400 max-w-md mx-auto mb-5 leading-relaxed">
                Generate a verified report using customer complaint, worker work notes, completed checklists, and confirmed spare parts.
              </p>
              {userRole === 'WORKER' || userRole === 'ADMIN' ? (
                <button
                  onClick={handleGenerateReport}
                  disabled={generating}
                  className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl bg-teal-700 hover:bg-teal-800 text-white text-xs font-semibold shadow-md transition disabled:opacity-60 cursor-pointer"
                >
                  <Sparkles className="w-4 h-4" />
                  {generating ? (t.generatingRepairReport || 'Gemma 4 Drafting Report...') : (t.generateRepairReportBtn || 'Generate AI Repair Report')}
                </button>
              ) : (
                <p className="text-xs text-slate-400 italic">
                  The servicing cooperative worker will generate and verify this report upon completing the physical repair.
                </p>
              )}
            </div>
          ) : (
            <div className="space-y-5">
              {/* Report Title & Metadata Card */}
              <div className="p-4 rounded-xl bg-slate-50 dark:bg-slate-850 border border-slate-200/80 dark:border-slate-800 space-y-3">
                <div className="flex items-center justify-between">
                  <span className="text-xs font-bold uppercase tracking-wider text-teal-700 dark:text-teal-400 flex items-center gap-1.5">
                    <ShieldCheck className="w-4 h-4" /> Help Nest Cooperative Service Certificate
                  </span>
                  {userRole !== 'CUSTOMER' && !isEditing && (
                    <button
                      onClick={() => setIsEditing(true)}
                      className="text-xs font-semibold text-slate-600 dark:text-slate-300 hover:text-teal-700 flex items-center gap-1 hover:underline cursor-pointer"
                    >
                      <Edit3 className="w-3.5 h-3.5" /> Edit Report
                    </button>
                  )}
                </div>

                {isEditing ? (
                  <div>
                    <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1">
                      Report Title
                    </label>
                    <input
                      type="text"
                      value={title}
                      onChange={(e) => setTitle(e.target.value)}
                      className="w-full px-3 py-2 text-sm rounded-lg border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-900 text-slate-900 dark:text-white"
                    />
                  </div>
                ) : (
                  <h4 className="text-base font-bold text-slate-900 dark:text-white">{title}</h4>
                )}

                <div className="grid grid-cols-2 md:grid-cols-4 gap-2 pt-2 text-xs text-slate-600 dark:text-slate-400 border-t border-slate-200 dark:border-slate-800">
                  <div>
                    <span className="text-slate-400 block">Customer:</span>
                    <strong className="text-slate-900 dark:text-slate-200">{booking.customerName}</strong>
                  </div>
                  <div>
                    <span className="text-slate-400 block">Assigned Worker:</span>
                    <strong className="text-slate-900 dark:text-slate-200">{booking.workerName}</strong>
                  </div>
                  <div>
                    <span className="text-slate-400 block">Service Date:</span>
                    <strong className="text-slate-900 dark:text-slate-200">{booking.preferredDate}</strong>
                  </div>
                  <div>
                    <span className="text-slate-400 block">Model Engine:</span>
                    <span className="font-mono text-teal-700 dark:text-teal-400">{report?.modelUsed || 'Gemma 4 AI'}</span>
                  </div>
                </div>
              </div>

              {/* 1. Original Reported Problem */}
              <div className="space-y-1.5">
                <label className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400">
                  1. {t.reportedProblem || 'Original Reported Problem'}
                </label>
                {isEditing ? (
                  <textarea
                    rows={2}
                    value={originalProblem}
                    onChange={(e) => setOriginalProblem(e.target.value)}
                    className="w-full px-3 py-2 text-xs rounded-lg border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-900 text-slate-900 dark:text-white"
                  />
                ) : (
                  <p className="text-xs p-3 rounded-lg bg-slate-50 dark:bg-slate-850/60 border border-slate-200 dark:border-slate-800 text-slate-800 dark:text-slate-200 leading-relaxed">
                    {originalProblem}
                  </p>
                )}
              </div>

              {/* 2. Work Performed */}
              <div className="space-y-2">
                <label className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400 flex items-center justify-between">
                  <span>2. {t.workPerformedLabel || 'Work Performed'}</span>
                  {isEditing && <span className="text-[10px] text-teal-700 lowercase font-normal">(add or remove items)</span>}
                </label>
                <div className="space-y-1.5">
                  {workPerformed.map((item, idx) => (
                    <div
                      key={idx}
                      className="text-xs p-2.5 rounded-lg bg-teal-50/50 dark:bg-teal-950/30 border border-teal-200/60 dark:border-teal-900/50 text-teal-900 dark:text-teal-200 flex items-start justify-between gap-2"
                    >
                      <span className="flex items-start gap-2">
                        <CheckCircle2 className="w-3.5 h-3.5 text-teal-600 shrink-0 mt-0.5" />
                        <span>{item}</span>
                      </span>
                      {isEditing && (
                        <button
                          onClick={() => setWorkPerformed((prev) => prev.filter((_, i) => i !== idx))}
                          className="text-slate-400 hover:text-rose-600 transition"
                        >
                          <Trash2 className="w-3.5 h-3.5" />
                        </button>
                      )}
                    </div>
                  ))}
                  {isEditing && (
                    <div className="flex gap-2 pt-1">
                      <input
                        type="text"
                        placeholder="Add completed work step..."
                        value={newWorkItem}
                        onChange={(e) => setNewWorkItem(e.target.value)}
                        onKeyDown={(e) => {
                          if (e.key === 'Enter' && newWorkItem.trim()) {
                            e.preventDefault();
                            setWorkPerformed((prev) => [...prev, newWorkItem.trim()]);
                            setNewWorkItem('');
                          }
                        }}
                        className="flex-1 px-3 py-1.5 text-xs rounded-lg border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-900 text-slate-900 dark:text-white"
                      />
                      <button
                        onClick={() => {
                          if (newWorkItem.trim()) {
                            setWorkPerformed((prev) => [...prev, newWorkItem.trim()]);
                            setNewWorkItem('');
                          }
                        }}
                        className="px-3 py-1.5 text-xs rounded-lg bg-teal-700 text-white font-semibold flex items-center gap-1 cursor-pointer"
                      >
                        <Plus className="w-3.5 h-3.5" /> Add
                      </button>
                    </div>
                  )}
                </div>
              </div>

              {/* 3. Confirmed Parts & Materials */}
              <div className="space-y-2">
                <label className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400">
                  3. {t.partsUsedLabel || 'Confirmed Parts & Supplies Used'}
                </label>
                {parts.length === 0 && !isEditing ? (
                  <p className="text-xs p-3 rounded-lg bg-slate-50 dark:bg-slate-850 border border-slate-200 dark:border-slate-800 text-slate-500 italic">
                    {t.noPartsUsedNotice || 'No replacement parts used (Labor only)'}
                  </p>
                ) : (
                  <div className="space-y-1.5">
                    {parts.map((p, idx) => (
                      <div
                        key={idx}
                        className="text-xs p-2.5 rounded-lg bg-slate-50 dark:bg-slate-850 border border-slate-200 dark:border-slate-800 text-slate-800 dark:text-slate-200 flex items-center justify-between"
                      >
                        <div className="flex items-center gap-2">
                          <Wrench className="w-3.5 h-3.5 text-teal-700" />
                          <span className="font-medium">{p.name}</span>
                          <span className="text-slate-400">(Qty: {p.quantity})</span>
                          {p.costInr ? <span className="font-semibold text-teal-700">₹{p.costInr}</span> : null}
                          {p.confirmed && (
                            <span className="text-[10px] px-1.5 py-0.2 rounded bg-emerald-100 dark:bg-emerald-950 text-emerald-700 dark:text-emerald-300 font-semibold">
                              Confirmed
                            </span>
                          )}
                        </div>
                        {isEditing && (
                          <button
                            onClick={() => setParts((prev) => prev.filter((_, i) => i !== idx))}
                            className="text-slate-400 hover:text-rose-600 transition"
                          >
                            <Trash2 className="w-3.5 h-3.5" />
                          </button>
                        )}
                      </div>
                    ))}
                  </div>
                )}
                {isEditing && (
                  <div className="grid grid-cols-1 md:grid-cols-4 gap-2 pt-1">
                    <input
                      type="text"
                      placeholder="Part / Material Name"
                      value={newPartName}
                      onChange={(e) => setNewPartName(e.target.value)}
                      className="md:col-span-2 px-3 py-1.5 text-xs rounded-lg border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-900 text-slate-900 dark:text-white"
                    />
                    <input
                      type="number"
                      placeholder="Qty"
                      min="1"
                      value={newPartQty}
                      onChange={(e) => setNewPartQty(e.target.value)}
                      className="px-2 py-1.5 text-xs rounded-lg border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-900 text-slate-900 dark:text-white"
                    />
                    <button
                      onClick={() => {
                        if (newPartName.trim()) {
                          setParts((prev) => [
                            ...prev,
                            {
                              name: newPartName.trim(),
                              quantity: Math.max(1, Number(newPartQty) || 1),
                              costInr: newPartCost ? Number(newPartCost) : undefined,
                              confirmed: true,
                            },
                          ]);
                          setNewPartName('');
                          setNewPartQty('1');
                          setNewPartCost('');
                        }
                      }}
                      className="px-3 py-1.5 text-xs rounded-lg bg-teal-700 text-white font-semibold flex items-center justify-center gap-1 cursor-pointer"
                    >
                      <Plus className="w-3.5 h-3.5" /> Add Part
                    </button>
                  </div>
                )}
              </div>

              {/* 4. Outstanding Issues & Maintenance Suggestions Grid */}
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                {/* Outstanding Issues */}
                <div className="space-y-1.5">
                  <label className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400">
                    4. {t.outstandingIssuesLabel || 'Outstanding Issues'}
                  </label>
                  <div className="space-y-1">
                    {outstandingIssues.map((oi, idx) => (
                      <div
                        key={idx}
                        className="text-xs p-2 rounded-lg bg-slate-50 dark:bg-slate-850 border border-slate-200 dark:border-slate-800 text-slate-700 dark:text-slate-300 flex items-center justify-between"
                      >
                        <span>• {oi}</span>
                        {isEditing && (
                          <button
                            onClick={() => setOutstandingIssues((prev) => prev.filter((_, i) => i !== idx))}
                            className="text-slate-400 hover:text-rose-600"
                          >
                            <Trash2 className="w-3 h-3" />
                          </button>
                        )}
                      </div>
                    ))}
                    {isEditing && (
                      <div className="flex gap-1.5 pt-1">
                        <input
                          type="text"
                          placeholder="Add remaining issue..."
                          value={newOutstandingItem}
                          onChange={(e) => setNewOutstandingItem(e.target.value)}
                          className="flex-1 px-2.5 py-1 text-xs rounded-lg border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-900"
                        />
                        <button
                          onClick={() => {
                            if (newOutstandingItem.trim()) {
                              setOutstandingIssues((prev) => [...prev, newOutstandingItem.trim()]);
                              setNewOutstandingItem('');
                            }
                          }}
                          className="px-2 py-1 text-xs rounded bg-slate-700 text-white font-semibold"
                        >
                          +
                        </button>
                      </div>
                    )}
                  </div>
                </div>

                {/* Maintenance Suggestions */}
                <div className="space-y-1.5">
                  <label className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400">
                    5. {t.maintenanceSuggestionsLabel || 'Maintenance Suggestions'}
                  </label>
                  <div className="space-y-1">
                    {maintenanceSuggestions.map((ms, idx) => (
                      <div
                        key={idx}
                        className="text-xs p-2 rounded-lg bg-emerald-50/50 dark:bg-emerald-950/20 border border-emerald-200/50 dark:border-emerald-900/40 text-emerald-900 dark:text-emerald-300 flex items-center justify-between"
                      >
                        <span>• {ms}</span>
                        {isEditing && (
                          <button
                            onClick={() => setMaintenanceSuggestions((prev) => prev.filter((_, i) => i !== idx))}
                            className="text-slate-400 hover:text-rose-600"
                          >
                            <Trash2 className="w-3 h-3" />
                          </button>
                        )}
                      </div>
                    ))}
                    {isEditing && (
                      <div className="flex gap-1.5 pt-1">
                        <input
                          type="text"
                          placeholder="Add preventive maintenance tip..."
                          value={newMaintenanceItem}
                          onChange={(e) => setNewMaintenanceItem(e.target.value)}
                          className="flex-1 px-2.5 py-1 text-xs rounded-lg border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-900"
                        />
                        <button
                          onClick={() => {
                            if (newMaintenanceItem.trim()) {
                              setMaintenanceSuggestions((prev) => [...prev, newMaintenanceItem.trim()]);
                              setNewMaintenanceItem('');
                            }
                          }}
                          className="px-2 py-1 text-xs rounded bg-teal-700 text-white font-semibold"
                        >
                          +
                        </button>
                      </div>
                    )}
                  </div>
                </div>
              </div>

              {/* 6. Customer Summary */}
              <div className="space-y-1.5">
                <label className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400">
                  6. {t.customerSummaryLabel || 'Summary for Customer'}
                </label>
                {isEditing ? (
                  <textarea
                    rows={2}
                    value={customerSummary}
                    onChange={(e) => setCustomerSummary(e.target.value)}
                    className="w-full px-3 py-2 text-xs rounded-lg border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-900 text-slate-900 dark:text-white"
                  />
                ) : (
                  <p className="text-xs p-3 rounded-lg bg-slate-50 dark:bg-slate-850/60 border border-slate-200 dark:border-slate-800 text-slate-800 dark:text-slate-200 leading-relaxed font-medium">
                    {customerSummary}
                  </p>
                )}
              </div>
            </div>
          )}
        </div>

        {/* Modal Footer */}
        <div className="p-4 border-t border-slate-100 dark:border-slate-800 bg-slate-50/60 dark:bg-slate-900/60 flex items-center justify-between gap-3">
          <div className="text-xs text-slate-400">
            {report?.workerApprovedAt ? (
              <span className="flex items-center gap-1.5 text-emerald-600 dark:text-emerald-400 font-semibold">
                <CheckCircle2 className="w-4 h-4" /> Approved on {new Date(report.workerApprovedAt).toLocaleDateString()}
              </span>
            ) : isEditing ? (
              <span className="italic text-amber-600 dark:text-amber-400">Editing draft report</span>
            ) : (
              <span>Help Nest Cooperative Quality Standard</span>
            )}
          </div>

          <div className="flex items-center gap-2">
            {(report || workPerformed.length > 0) && (
              <button
                onClick={handleDownloadPdf}
                className="px-4 py-2 rounded-xl border border-slate-300 dark:border-slate-700 hover:bg-slate-100 dark:hover:bg-slate-800 text-slate-700 dark:text-slate-200 text-xs font-semibold flex items-center gap-1.5 transition cursor-pointer"
              >
                <Download className="w-3.5 h-3.5" />
                {t.downloadPdfReport || 'Download PDF Report'}
              </button>
            )}

            {(userRole === 'WORKER' || userRole === 'ADMIN') && isEditing && (
              <button
                onClick={handleSaveAndApprove}
                disabled={saving}
                className="px-4 py-2 rounded-xl bg-teal-700 hover:bg-teal-800 text-white text-xs font-semibold shadow-md flex items-center gap-1.5 transition disabled:opacity-60 cursor-pointer"
              >
                <Save className="w-3.5 h-3.5" />
                {saving ? 'Saving...' : (t.saveAndApproveReport || 'Approve & Save Report')}
              </button>
            )}

            <button
              onClick={onClose}
              className="px-4 py-2 rounded-xl bg-slate-200 dark:bg-slate-800 hover:bg-slate-300 dark:hover:bg-slate-700 text-slate-700 dark:text-slate-300 text-xs font-semibold transition cursor-pointer"
            >
              {t.closeBtn || 'Close'}
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
